export const DEFAULT_LANGUAGE_CODE = 'en';

export function getLanguageConfig(code = DEFAULT_LANGUAGE_CODE) {
  const normalized = (code || DEFAULT_LANGUAGE_CODE).toLowerCase();
  return (
    SUPPORTED_LANGUAGES.find((lang) => lang.code === normalized) ||
    SUPPORTED_LANGUAGES.find((lang) => lang.code === DEFAULT_LANGUAGE_CODE)
  );
}

export function getLanguageName(code = DEFAULT_LANGUAGE_CODE) {
  const config = getLanguageConfig(code);
  return config ? `${config.flag} ${config.nativeName}` : 'English';
}

export function getLocalizedStatus(code, key, fallback = '') {
  const config = getLanguageConfig(code);
  if (config?.status && config.status[key]) {
    return config.status[key];
  }
  const enConfig = getLanguageConfig('en');
  return enConfig?.status?.[key] || fallback;
}
